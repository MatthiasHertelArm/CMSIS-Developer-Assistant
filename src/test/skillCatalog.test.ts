import * as assert from 'assert';
import * as fs from 'fs';
import * as path from 'path';
import { DatabaseSync } from 'node:sqlite';
import { TOOL_CONTRACT_DOC, ToolContract, parseToolContract } from '../core/toolContract';
import {
    SKILL_CATEGORY_LABELS,
    SKILL_CATEGORY_ORDER,
    SkillCatalog,
    SkillCatalogEntry,
    bundledSkillNames,
    extractSkillReferences,
    installSet,
    isBundledSkill,
    loadSkillCatalog,
    parseSkillFrontmatter,
} from '../utils/skillCatalog';

/** The one skill the extension installs: the health check (skills/cmsis-help). */
const HELP_SKILL_NAME = 'cmsis-help';

/**
 * `skills/catalog.json` is generated by `npm run skills:sync`; the runtime
 * installs its `installed` entries, and the knowledge base reads the rest as
 * the sources of procedure units. These tests pin the catalog to the
 * directories on disk and the config, so a forgotten re-sync, a hand-over to
 * a procedure the index does not have, or a vendored copy creeping back in
 * fails here rather than in someone else's harness.
 */
suite('Agent skill catalog', () => {

    const repoRoot = path.resolve(__dirname, '..', '..', '..');
    const skillsDir = path.join(repoRoot, 'skills');
    const coreIndex = path.join(repoRoot, 'resources', 'knowledge', 'core.db');
    const syncConfig = (): { bundled: { name: string }[]; categories: { id: string; workflow: string[] }[]; installed: string[] } =>
        JSON.parse(fs.readFileSync(path.join(repoRoot, 'scripts', 'skills.config.json'), 'utf8'));

    const catalog = (): SkillCatalog => loadSkillCatalog(repoRoot);
    const skillName = /^[a-z]+(?:-[a-z0-9]+)+$/;

    test('the catalog ships, and it is the extension\'s own skills alone: nothing vendored, no router', () => {
        assert.ok(fs.existsSync(path.join(skillsDir, 'catalog.json')));
        assert.strictEqual(catalog().schemaVersion, 1);
        assert.strictEqual(catalog().source, undefined, 'the catalog names no upstream commit');
        for (const entry of catalog().skills) {
            assert.ok(entry.source === 'bundled' || entry.source === 'extension', `${entry.name}: source ${entry.source}`);
            assert.strictEqual(entry.kind, 'skill', `${entry.name}: kind ${entry.kind}`);
        }
        for (const gone of ['cmsis-skills', 'cmsis-skills.lock.json', 'cmsis-project']) {
            assert.ok(!fs.existsSync(path.join(skillsDir, gone)), `skills/${gone} is back`);
        }
    });

    test('every skill directory is in the catalog and vice versa, in the order of the config', () => {
        const onDisk = fs.readdirSync(skillsDir, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
        assert.deepStrictEqual(catalog().skills.map(entry => entry.name).sort(), onDisk, 'run `npm run skills:sync`');
        assert.deepStrictEqual(syncConfig().bundled.map(entry => entry.name).sort(), onDisk);
    });

    test('every entry points at a real SKILL.md whose frontmatter agrees with the catalog', () => {
        for (const entry of catalog().skills) {
            const skillFile = path.join(repoRoot, entry.path, 'SKILL.md');
            assert.ok(fs.existsSync(skillFile), `${entry.name}: missing ${skillFile}`);
            assert.strictEqual(path.basename(entry.path), entry.name, `${entry.name}: directory name must equal the skill name`);
            const frontmatter = parseSkillFrontmatter(fs.readFileSync(skillFile, 'utf8'));
            assert.ok(frontmatter, `${entry.name}: unparseable frontmatter`);
            assert.strictEqual(frontmatter.name, entry.name);
            assert.strictEqual(frontmatter.description, entry.description);
        }
    });

    test('names are unique and categories are known', () => {
        const names = catalog().skills.map(entry => entry.name);
        assert.strictEqual(new Set(names).size, names.length, 'duplicate skill names');
        for (const entry of catalog().skills) {
            assert.ok(SKILL_CATEGORY_ORDER.includes(entry.category), `${entry.name}: unknown category ${entry.category}`);
        }
    });

    test('the bundled entries are the board-layer, bootstrap, pack-docs, debugging and help skills, nothing else', () => {
        const bundled = catalog().skills.filter(entry => entry.source === 'bundled');
        assert.deepStrictEqual(bundled.map(entry => [entry.name, entry.category, entry.path]), [
            ['add-board-layer', 'project', 'skills/add-board-layer'],
            ['cmsis-bootstrap', 'project', 'skills/cmsis-bootstrap'],
            ['cmsis-pack-docs', 'bring-up', 'skills/cmsis-pack-docs'],
            ['cmsis-debug-live', 'debug', 'skills/cmsis-debug-live'],
            [HELP_SKILL_NAME, 'help', `skills/${HELP_SKILL_NAME}`],
        ]);
        assert.deepStrictEqual(bundledSkillNames(catalog()),
            ['add-board-layer', 'cmsis-bootstrap', 'cmsis-pack-docs', 'cmsis-debug-live', HELP_SKILL_NAME]);
    });

    test('the extension\'s hidden skills are reached through a hand-over of another', () => {
        const own = catalog().skills.filter(entry => entry.source === 'extension');
        assert.deepStrictEqual(own.map(entry => [entry.name, entry.category, entry.path]), [
            ['cmsis-debugger-setup', 'project', 'skills/cmsis-debugger-setup'],
            ['start-cmsis-project', 'project', 'skills/start-cmsis-project'],
            ['debugger-troubleshooting', 'debug', 'skills/debugger-troubleshooting'],
            ['fvp-debug-setup', 'debug', 'skills/fvp-debug-setup'],
        ]);
        const reachedFrom = (name: string): string[] => catalog().skills.filter(entry => entry.dependsOn.includes(name)).map(entry => entry.name);
        for (const entry of own) {
            assert.ok(!isBundledSkill(entry) && !entry.invocable, entry.name);
            assert.ok(entry.displayName?.startsWith('CMSIS: '), `${entry.name}: display name`);
            assert.ok(entry.shortDescription, `${entry.name}: short description`);
            assert.ok(reachedFrom(entry.name).length > 0, `${entry.name}: no skill hands over to it`);
        }
    });

    test('the installed set is cmsis-help alone, within the Agent Skills description limit', () => {
        const set = installSet(catalog());
        assert.deepStrictEqual([...set.visible, ...set.hidden], [HELP_SKILL_NAME]);
        assert.deepStrictEqual(syncConfig().installed, [HELP_SKILL_NAME]);
        for (const entry of catalog().skills) {
            assert.strictEqual(entry.invocable, entry.source === 'bundled', `${entry.name}: invocable`);
            if (entry.installed) {
                assert.ok(entry.description.length <= 1024, `${entry.name}: description of ${entry.description.length} chars`);
            }
        }
    });

    test('every dependency resolves to a catalog skill and nothing depends on itself', () => {
        const names = new Set(catalog().skills.map(entry => entry.name));
        for (const entry of catalog().skills) {
            for (const dependency of entry.dependsOn) {
                assert.ok(names.has(dependency), `${entry.name} depends on unknown ${dependency}`);
                assert.notStrictEqual(dependency, entry.name, `${entry.name} depends on itself`);
            }
        }
    });

    test('the $name references to the extension\'s skills are recorded as dependencies', () => {
        const names = new Set(catalog().skills.map(entry => entry.name));
        for (const entry of catalog().skills.filter(e => e.name !== HELP_SKILL_NAME)) {
            const markdown = fs.readFileSync(path.join(repoRoot, entry.path, 'SKILL.md'), 'utf8');
            const expected = extractSkillReferences(markdown).filter(ref => names.has(ref) && ref !== entry.name);
            assert.deepStrictEqual([...entry.dependsOn].sort(), expected,
                `${entry.name}: dependsOn is out of date — run \`npm run skills:sync\``);
        }
    });

    test('every hand-over, in a skill or a category workflow, names a skill of the extension or a procedure of the pinned index', function () {
        // A hand-over to a procedure the index does not have is a dead end for the agent: 2.5.15
        // shipped $start-cmsis-project and $csolution-retarget that way. CI's test job has no index.
        if (!fs.existsSync(coreIndex)) {
            this.skip();
        }
        const db = new DatabaseSync(coreIndex, { readOnly: true });
        const procedures = new Set(db.prepare("SELECT id FROM nodes WHERE type = 'procedure' AND id LIKE 'proc-%'").all()
            .map(row => String(row.id).slice('proc-'.length)));
        db.close();
        const reachable = new Set([...catalog().skills.map(entry => entry.name), ...procedures]);
        const texts: [string, string][] = [
            ...catalog().skills.map((entry): [string, string] => [entry.name, fs.readFileSync(path.join(repoRoot, entry.path, 'SKILL.md'), 'utf8')]),
            ...syncConfig().categories.map((category): [string, string] => [`category ${category.id}`, category.workflow.join('\n')]),
        ];
        for (const [name, text] of texts) {
            const unresolved = extractSkillReferences(text).filter(ref => skillName.test(ref) && ref !== name && !reachable.has(ref));
            assert.deepStrictEqual(unresolved, [], `${name}: hands over to procedure(s) the core index does not have`);
        }
    });

    /**
     * The help skill is what an agent answers "what can I ask for?" from. It
     * is generated from the catalog, package.json and the generator config,
     * and re-rendered here: a new command, setting or skill that is not
     * reflected in the shipped file fails this suite, not a user's question.
     */
    suite(HELP_SKILL_NAME, () => {
        const helpSkill = (): SkillCatalogEntry => {
            const found = catalog().skills.find(entry => entry.name === HELP_SKILL_NAME);
            assert.ok(found, 'cmsis-help is not in the catalog');
            return found;
        };
        const skillMd = (): string => fs.readFileSync(path.join(repoRoot, 'skills', HELP_SKILL_NAME, 'SKILL.md'), 'utf8');

        test('is the one skill the extension installs', () => {
            assert.deepStrictEqual(catalog().skills.filter(entry => entry.installed).map(entry => entry.name), [HELP_SKILL_NAME]);
            assert.match(skillMd(), new RegExp(`^---\\nname: ${HELP_SKILL_NAME}\\n`));
        });

        test('carries the tool rules and the shell-to-tool table copied from the contract', () => {
            const contract = parseToolContract(fs.readFileSync(path.join(repoRoot, 'docs', TOOL_CONTRACT_DOC), 'utf8'));
            assert.ok(skillMd().includes(contract.rules), 'the rules block is not in the skill');
            assert.ok(skillMd().includes(contract.table), 'the shell-to-tool table is not in the skill');
        });

        test('checks the session with the read-only tools and routes to the debug topics and the knowledge', () => {
            for (const tool of ['get_session_status', 'check_target_connection', 'get_recent_problems', 'get_debug_instructions', 'knowledge_search']) {
                assert.ok(skillMd().includes(tool), `${tool} is not named`);
            }
        });

        test('its description is quoted and within the Agent Skills limit', () => {
            assert.ok(helpSkill().description.length <= 1024, `description of ${helpSkill().description.length} chars`);
            assert.match(skillMd(), /^description: "/m);
        });
    });

    suite('installSet', () => {
        const entry = (name: string, category: SkillCatalogEntry['category'], kind: SkillCatalogEntry['kind'], source: SkillCatalogEntry['source'],
            invocable: boolean, installed: boolean, dependsOn: string[] = []): SkillCatalogEntry =>
            ({ name, description: '', category, kind, source, path: `skills/${name}`, dependsOn, invocable, installed });
        const fake: SkillCatalog = {
            schemaVersion: 1,
            source: { repository: 'r', sha: 'abc', sourcePath: 'p' },
            skills: [
                entry('r-project', 'project', 'router', 'generated', true, false, ['env', 'setup']),
                entry('env', 'project', 'skill', 'cmsis-skills', false, false),
                entry('setup', 'project', 'skill', 'extension', false, false, ['trouble']),
                entry('cmsis-debug-live', 'debug', 'skill', 'bundled', true, false),
                entry('trouble', 'debug', 'skill', 'extension', false, false),
                entry('ci', 'devops', 'skill', 'cmsis-skills', true, false),
                entry('cmsis-help', 'help', 'skill', 'bundled', true, true),
            ],
        };

        test('lists only the installed entries, visible and hidden, in catalog order', () => {
            assert.deepStrictEqual(installSet(fake), { visible: ['cmsis-help'], hidden: [] });
            const withHidden = { ...fake, skills: fake.skills.map(skill => (skill.name === 'trouble' ? { ...skill, installed: true } : skill)) };
            assert.deepStrictEqual(installSet(withHidden), { visible: ['cmsis-help'], hidden: ['trouble'] });
        });

        test('an empty catalog installs nothing', () => {
            assert.deepStrictEqual(installSet({ ...fake, skills: [] }), { visible: [], hidden: [] });
        });

        test('the shipped catalog installs cmsis-help alone and every other entry is a unit only', () => {
            assert.deepStrictEqual(installSet(catalog()), { visible: [HELP_SKILL_NAME], hidden: [] });
            for (const skill of catalog().skills.filter(skill => skill.name !== HELP_SKILL_NAME)) {
                assert.strictEqual(skill.installed, false, `${skill.name} is installed`);
            }
        });
    });

    /**
     * Upstream's `ethos-u` category is known, and the extension has no skill
     * of it, so it must leave every generated file as it is.
     */
    suite('a category without skills (ethos-u)', () => {
        test('ethos-u is a known category with a label, placed after the CMSIS ones', () => {
            assert.deepStrictEqual(SKILL_CATEGORY_ORDER, ['project', 'bring-up', 'debug', 'pack', 'ethos-u', 'devops', 'help']);
            assert.strictEqual(SKILL_CATEGORY_LABELS['ethos-u'], 'Ethos-U NPU');
            for (const category of SKILL_CATEGORY_ORDER) {
                assert.ok(SKILL_CATEGORY_LABELS[category], `${category} has no label`);
            }
        });

        test('with no skills it gets no help section', () => {
            assert.ok(!catalog().skills.some(entry => entry.category === 'ethos-u'));
            const help = fs.readFileSync(path.join(skillsDir, HELP_SKILL_NAME, 'SKILL.md'), 'utf8');
            assert.ok(!help.includes('Ethos-U'), 'the shipped help names no empty category');
        });
    });

    suite('frontmatter parsing', () => {
        test('reads plain and double-quoted scalars', () => {
            const plain = parseSkillFrontmatter('---\nname: a\ndescription: Do the thing. Use when asked.\n---\n# A\n');
            assert.deepStrictEqual([plain?.name, plain?.description], ['a', 'Do the thing. Use when asked.']);
            const quoted = parseSkillFrontmatter('---\nname: b\ndescription: "Build: a record, \\"verified\\"."\nlicense: MIT\n---\n');
            assert.strictEqual(quoted?.description, 'Build: a record, "verified".');
        });

        test('tolerates CRLF and rejects files without a fence', () => {
            assert.strictEqual(parseSkillFrontmatter('---\r\nname: c\r\ndescription: d\r\n---\r\nbody')?.name, 'c');
            assert.strictEqual(parseSkillFrontmatter('# no frontmatter\n'), null);
        });

        test('extracts $name references, lowercase-hyphenated only', () => {
            const refs = extractSkillReferences('after `$debug-knowledge` and $trace-knowledge; not $HOME, not ${var}, not $a.');
            assert.deepStrictEqual(refs, ['debug-knowledge', 'trace-knowledge']);
        });
    });
});
